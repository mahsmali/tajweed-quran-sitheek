/**
 * Offline dataset builder + engine verification harness.
 *
 *   npm run seed
 *
 * 1. Pulls Uthmani text for the core teaching surahs from api.quran.com.
 * 2. Writes `src/lib/pipeline/seed.ts` so the app still works with no network.
 * 3. Writes `db/seed/verse_1_2.json` — the worked example of the storage shape.
 * 4. Runs the Tajweed engine over every seeded verse and prints a colour dump,
 *    which is how rule changes get eyeballed before they reach the UI.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { analyzeVerse, resolveGlyphRuns, uniqueRuleIds } from '../src/lib/tajweed/engine';
import { getRule, FAMILY_STYLE } from '../src/lib/tajweed/rules';
import { makharijForText } from '../src/lib/tajweed/makharij';
import { estimateWordTimings } from '../src/lib/pipeline/timing';
import { stripMarks } from '../src/lib/arabic/unicode';

const API = 'https://api.quran.com/api/v4';
/**
 * Every surah the 30-day curriculum draws practice material from.
 * 3 and 48 are here for the two complete-alphabet verses (3:154, 48:29) —
 * see `src/lib/content/showcaseVerses.ts`.
 */
const SEED_SURAHS = [1, 3, 48, 50, 68, 78, 101, 103, 104, 105, 106, 107, 108, 110, 112, 113, 114];

const ANSI: Record<string, string> = {
  madd: '\x1b[31m', ghunnah: '\x1b[32m', qalqalah: '\x1b[34m',
  makharij: '\x1b[33m', silent: '\x1b[90m', none: '\x1b[37m', izhar: '\x1b[37m',
};
const RESET = '\x1b[0m';

interface SeedVerse { ayah: number; text: string; translation: string | null }
interface SeedChapter {
  nameArabic: string; nameSimple: string; translatedName: string;
  revelationPlace: string; bismillahPre: boolean; verses: SeedVerse[];
}

async function fetchChapter(surah: number): Promise<SeedChapter> {
  const [c, v] = await Promise.all([
    fetch(`${API}/chapters/${surah}?language=en`).then((r) => r.json()),
    fetch(
      `${API}/verses/by_chapter/${surah}?words=true&per_page=300&word_fields=text_uthmani` +
        `&fields=text_uthmani&translations=20`,
    ).then((r) => r.json()),
  ]);
  return {
    nameArabic: c.chapter.name_arabic,
    nameSimple: c.chapter.name_simple,
    translatedName: c.chapter.translated_name.name,
    revelationPlace: c.chapter.revelation_place,
    bismillahPre: c.chapter.bismillah_pre,
    verses: v.verses.map((x: any) => ({
      ayah: x.verse_number,
      text: x.words.filter((w: any) => w.char_type_name === 'word').map((w: any) => w.text_uthmani).join(' '),
      translation:
        x.translations?.[0]?.text
          ?.replace(/<sup[^>]*>.*?<\/sup>/gi, '')
          .replace(/<[^>]*>/g, '')
          .replace(/\s+/g, ' ')
          .trim() || null,
    })),
  };
}

function dumpVerse(surah: number, ayah: number, text: string) {
  const words = text.split(/\s+/).filter(Boolean);
  const spansByWord = analyzeVerse(words);
  const line = words
    .map((w, i) =>
      resolveGlyphRuns(w, spansByWord[i])
        .map((run) => `${ANSI[run.family] ?? ANSI.none}${run.text}${RESET}`)
        .join(''),
    )
    .join(' ');
  console.log(`\n  ${surah}:${ayah}  ${line}`);
  words.forEach((w, i) => {
    const ids = uniqueRuleIds(spansByWord[i]);
    if (!ids.length) return;
    const tags = ids.map((id) => `${ANSI[getRule(id).family]}${getRule(id).label}${RESET}`).join(', ');
    console.log(`        ${w.padEnd(18)} ${tags}`);
  });
}

async function main() {
  const chapters: Record<number, SeedChapter> = {};
  for (const s of SEED_SURAHS) {
    process.stdout.write(`  fetching surah ${s} … `);
    chapters[s] = await fetchChapter(s);
    console.log(`${chapters[s].verses.length} verses`);
  }

  // ── 1. bundled offline text ──────────────────────────────────────────────
  const seedPath = resolve(process.cwd(), 'src/lib/pipeline/seed.ts');
  const header = `/* AUTO-GENERATED by \`npm run seed\` — do not edit by hand.
 * Offline Uthmani text for the core teaching surahs, so the reader, the
 * curriculum and the quiz all keep working with no network access. */

export interface SeedVerse { ayah: number; text: string; translation: string | null }
export interface SeedChapter {
  nameArabic: string; nameSimple: string; translatedName: string;
  revelationPlace: string; bismillahPre: boolean; verses: SeedVerse[];
}

export const SEED_CHAPTERS: Record<number, SeedChapter> = `;
  writeFileSync(seedPath, `${header}${JSON.stringify(chapters, null, 2)};\n`, 'utf8');
  console.log(`\n  wrote ${seedPath}`);

  // ── 2. worked storage example: one verse, fully normalised ───────────────
  const demo = chapters[1].verses[1]; // 1:2  ٱلْحَمْدُ لِلَّهِ رَبِّ ٱلْعَٰلَمِينَ
  const words = demo.text.split(/\s+/).filter(Boolean);
  const spans = analyzeVerse(words);
  const est = estimateWordTimings(words, 5590);
  const pad = (n: number) => String(n).padStart(3, '0');
  const doc = {
    verse_key: '1:2',
    surah: 1,
    ayah: 2,
    text_uthmani: demo.text,
    translation: demo.translation,
    engine_version: '1.4.0',
    audio: {
      verse_audio_url: 'https://verses.quran.com/Alafasy/mp3/001002.mp3',
      reciter_id: 7,
      reciter_name: 'Mishari Rashid al-Afasy',
      duration_ms: 5590,
      timing_source: 'quran.com-segments',
    },
    words: words.map((w, i) => ({
      id: `1:2:${i + 1}`,
      position: i + 1,
      text_uthmani: w,
      text_simple: stripMarks(w),
      audio_url: `https://audio.qurancdn.com/wbw/001_002_${pad(i + 1)}.mp3`,
      timing: { start_ms: est[i].startMs, end_ms: est[i].endMs, source: 'estimated' },
      makharij: makharijForText(w),
      rule_ids: uniqueRuleIds(spans[i]),
      spans: spans[i].map((s) => ({
        rule_id: s.ruleId, family: s.family, char_start: s.start, char_end: s.end,
        text: s.text, counts: s.counts ?? null, note: s.note,
      })),
    })),
  };
  const jsonPath = resolve(process.cwd(), 'db/seed/verse_1_2.json');
  mkdirSync(dirname(jsonPath), { recursive: true });
  writeFileSync(jsonPath, JSON.stringify(doc, null, 2), 'utf8');
  console.log(`  wrote ${jsonPath}`);

  // ── 3. engine verification dump ──────────────────────────────────────────
  console.log('\n─── ENGINE OUTPUT ─────────────────────────────────────────────');
  for (const fam of Object.keys(FAMILY_STYLE)) {
    process.stdout.write(`${ANSI[fam] ?? ''}■${RESET} ${FAMILY_STYLE[fam as keyof typeof FAMILY_STYLE].label}   `);
  }
  console.log();
  for (const s of SEED_SURAHS) for (const v of chapters[s].verses) dumpVerse(s, v.ayah, v.text);
  console.log('\n───────────────────────────────────────────────────────────────\n');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
